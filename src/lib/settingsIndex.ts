/** Сравнение названий: без регистра и без «ё» — «неподключенные» находит «неподключённые» */
export function settingKey(text: string): string {
  return text.trim().toLowerCase().replace(/ё/g, "е");
}

/**
 * Поиск пункта по названию (или по названию блока).
 * Совпадения с начала названия идут первыми: «звук» сначала покажет
 * «Звук сообщения», а потом уже «Звуки событий».
 */
export function searchSettings(query: string): SettingEntry[] {
  const q = settingKey(query);
  if (!q) return [];
  const hits = SETTINGS_INDEX.filter(
    (e) => settingKey(e.label).includes(q) || (e.box ? settingKey(e.box).includes(q) : false),
  );
  return hits.sort(
    (a, b) => Number(settingKey(b.label).startsWith(q)) - Number(settingKey(a.label).startsWith(q)),
  );
}
