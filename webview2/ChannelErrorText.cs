using System.IO;
using System.Net;
using System.Net.Http;
using System.Net.Sockets;
using System.Net.WebSockets;
using System.Text.Json;

namespace YawaChat;

/// <summary>
/// Объяснение сбоя для интерфейса. Тексты исключений от HTTP, сокета и самих
/// площадок могут содержать URL с ключом, токен или ответ сервера. Никогда не
/// пересылаем ex.Message как есть: выбираем только подготовленные фразы.
/// </summary>
internal static class ChannelErrorText
{
    public static string Describe(string platform, Exception ex)
    {
        // Эти сообщения создаём мы сами в коннекторах. Используем их лишь для
        // распознавания причины, а не для показа: серверный ответ и username
        // могут быть дописаны к тому же тексту.
        if (ex is InvalidOperationException)
        {
            var message = ex.Message;
            bool Has(string text) => message.Contains(text, StringComparison.OrdinalIgnoreCase);

            if (platform == "boosty")
            {
                if (Has("токен отклонён") || Has("не выдала доступ") || Has("отказ авторизации"))
                    return "Доступ к чату отклонён. Добавьте действующий токен аккаунта Boosty.";
                if (Has("токеном аккаунта"))
                    return "Для чтения чата Boosty нужен токен аккаунта. Добавьте канал заново с токеном.";
            }
            if (platform == "donationalerts")
            {
                if (Has("нет прав") || Has("socket_connection_token") || Has("подписка отклонена"))
                    return "Нет доступа к донатам. Проверьте права токена DonationAlerts и добавьте его заново.";
                if (Has("токен недействителен") || Has("вставьте токен"))
                    return "Токен DonationAlerts отсутствует или истёк. Добавьте канал заново с действующим токеном.";
            }
            if (platform == "donatepay" &&
                (Has("API-ключ") || Has("ключ отклонён") || Has("по ключу") ||
                 Has("Incorrect token") || Has("ключ не принят") || Has("канал донатов недоступен")))
                return "Не удалось получить доступ к донатам. Проверьте API-ключ DonatePay и добавьте канал заново.";
            if (platform == "memealerts")
            {
                if (Has("не подключён") || Has("раздел «Донаты»"))
                    return "Аккаунт MemeAlerts не подключён. Откройте раздел «Донаты» и нажмите «Подключить».";
                if (Has("Client ID"))
                    return "Укажите Client ID и Client Secret приложения MemeAlerts в разделе «Донаты».";
                if (Has("отозван") || Has("отклонён") || Has("переподключите аккаунт") ||
                    Has("подписка отклонена") || Has("нет токена"))
                    return "Доступ MemeAlerts истёк или отозван. Подключите аккаунт заново в разделе «Донаты».";
            }
            if (platform == "tiktok" && (Has("встроенный мост") || Has("Node.js не запущен")))
                return "Модуль TikTok не запустился. Перезапустите приложение или установите свежую версию.";
            if (platform == "youtube" &&
                (Has("страницы канала недоступны") || Has("страница эфира недоступна")))
                return "Не удалось открыть страницу канала на YouTube. Проверьте его адрес и доступность сайта.";

            if ((platform == "vkplay" || platform == "boosty") &&
                (Has("(401)") || Has("(403)")))
                return "Площадка отказала в доступе к каналу. Проверьте вход или доступность чата.";
            if (Has("не найден"))
                return "Канал не найден. Проверьте имя или ссылку и добавьте канал заново.";
            if (Has("не указан") || Has("не указано"))
                return "Не указан канал для подключения. Проверьте введённое имя или ссылку.";
            if (Has("подписка") && (Has("отклонена") || Has("нет подтверждения")))
                return "Площадка отклонила подключение к чату. Проверьте доступ к каналу и повторите попытку.";
            if (Has("отказ авторизации"))
                return "Площадка отказала в доступе к чату. Проверьте вход и повторите попытку.";
            if (Has("не удалось получить канал чата") || Has("не вернула канал чата") ||
                Has("пустой идентификатор") || Has("неожиданный ответ"))
                return "Площадка не вернула данные чата. Обновите приложение или повторите попытку позже.";
            if (Has("закрыл соединение") || Has("соединение закрыто") || Has("socket закрыт"))
                return "Соединение с чатом оборвалось. Приложение попробует подключиться снова.";
        }

        if (ex is HttpRequestException http)
        {
            if (http.StatusCode is not { } code)
                return "Не удалось связаться с площадкой. Проверьте подключение к интернету.";
            return code switch
            {
                HttpStatusCode.NotFound => "Канал не найден на площадке. Проверьте его имя или ссылку.",
                HttpStatusCode.Unauthorized or HttpStatusCode.Forbidden =>
                    "Площадка отказала в доступе. Проверьте вход или токен канала.",
                HttpStatusCode.TooManyRequests =>
                    "Площадка временно ограничила запросы. Подождите и попробуйте снова.",
                _ when (int)code >= 500 =>
                    "Сервер площадки сейчас не отвечает. Подождите и попробуйте снова.",
                _ => "Площадка отклонила запрос канала. Проверьте имя и попробуйте снова.",
            };
        }
        if (ex is TimeoutException or OperationCanceledException)
            return "Площадка не ответила вовремя при подключении. Проверьте сеть и попробуйте снова.";
        if (ex is WebSocketException or SocketException or IOException)
            return "Не удалось подключиться к чату. Проверьте сеть и повторите попытку.";
        if (ex is JsonException)
            return "Площадка вернула неожиданный ответ. Обновите приложение или попробуйте позже.";

        return "Не удалось подключить канал. Попробуйте переподключить его или проверьте сеть.";
    }
}
